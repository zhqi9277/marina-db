#!/bin/sh
# Install a `marina` launcher into a bin directory that is already on PATH.
# No sudo, no npm global prefix — works with nvm, pyenv, asdf, etc.
#
#   bash scripts/install-cli.sh                 # -> ~/.local/bin/marina
#   MARINA_BIN_DIR=/usr/local/bin bash scripts/install-cli.sh
#
# The launcher runs this checkout directly, so edits are picked up immediately.
# If you move the checkout, run this script again.
set -eu

REPO=$(cd "$(dirname "$0")/.." && pwd)
BIN_DIR=${MARINA_BIN_DIR:-$HOME/.local/bin}
LAUNCHER="$BIN_DIR/marina"
NODE_BIN=$(command -v node || true)

if [ -z "$NODE_BIN" ]; then
  echo "error: node not found on PATH (Node >= 18 required)" >&2
  exit 1
fi

if [ ! -f "$REPO/bin/marina.js" ]; then
  echo "error: $REPO/bin/marina.js is missing" >&2
  exit 1
fi

mkdir -p "$BIN_DIR"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# generated by marina/scripts/install-cli.sh — re-run it if the checkout moves
if command -v node >/dev/null 2>&1; then
  exec node "$REPO/bin/marina.js" "\$@"
fi
exec "$NODE_BIN" "$REPO/bin/marina.js" "\$@"
EOF
chmod +x "$LAUNCHER"

echo "installed: $LAUNCHER"
echo "  -> $NODE_BIN $REPO/bin/marina.js"

case ":$PATH:" in
  *":$BIN_DIR:"*)
    echo "ok: $BIN_DIR is already on PATH"
    ;;
  *)
    echo
    echo "note: $BIN_DIR is not on PATH. Add this to ~/.zshrc:"
    echo "  export PATH=\"$BIN_DIR:\$PATH\""
    ;;
esac

echo
echo "try: marina --version"
