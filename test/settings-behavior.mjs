// Port/account settings: real change flows against an isolated MARINA_HOME.
// Everything runs offline: TCP probes only touch loopback and no engine is run.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import test, { after } from 'node:test';

const HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'marina-settings-'));
process.env.MARINA_HOME = HOME;

const { buildCtx, engines } = await import('../src/registry.js');
const { validatePort, changePort, changeAccount } = await import('../src/settings.js');
const state = await import('../src/state.js');

after(() => fs.rmSync(HOME, { recursive: true, force: true }));

/** A port nothing listens on (bind, read, close). */
async function closedPort() {
  const srv = net.createServer();
  await new Promise((resolve) => srv.listen(0, '127.0.0.1', resolve));
  const { port } = srv.address();
  await new Promise((resolve) => srv.close(resolve));
  return port;
}

/** A port kept open for the duration of a test. */
async function listeningPort() {
  const srv = net.createServer();
  await new Promise((resolve) => srv.listen(0, '127.0.0.1', resolve));
  return { srv, port: srv.address().port };
}

test('validatePort accepts string digits and the 1/65535 boundaries', () => {
  assert.equal(validatePort('1'), 1);
  assert.equal(validatePort(1), 1);
  assert.equal(validatePort(65535), 65535);
  for (const bad of ['', ' ', null, undefined, '0', '65536', 0.5]) {
    assert.throws(() => validatePort(bad), /port must be 1\.\.65535/);
  }
});

test('a blank account user is rejected before any state is written', async () => {
  const ctx = buildCtx(engines.mongodb, { major: '7.0', version: '7.0.45', port: await closedPort() });
  await assert.rejects(changeAccount(ctx, { user: '   ' }), /account user cannot be empty/);
  assert.equal(fs.existsSync(path.join(HOME, 'state.json')), false);
});

test('changing mysql credentials while stopped is refused with a start hint', async () => {
  const port = await closedPort();
  const ctx = buildCtx(engines.mysql, { major: '8.4', version: '8.4.11', port });
  await assert.rejects(changeAccount(ctx, { password: 's3cret' }), /mysql is stopped — start it first/);
  // the default account is untouched
  assert.deepEqual(state.accountOf('mysql'), { user: 'root', password: 'root' });
});

test('changing a mariadb user while stopped is refused too', async () => {
  const ctx = buildCtx(engines.mariadb, { major: '11.4', version: '11.4.13', port: await closedPort() });
  await assert.rejects(changeAccount(ctx, { user: 'admin' }), /mariadb is stopped — start it first/);
});

test('postgres allows storing a user while stopped and says it applies later', async () => {
  const ctx = buildCtx(engines.postgres, { major: '17', version: '17.11', port: await closedPort() });
  const result = await changeAccount(ctx, { user: 'marina' });
  assert.deepEqual(result.account, { user: 'marina', password: null });
  assert.deepEqual(result.applied, []);
  assert.match(result.notes.join(' '), /stored only; applies on next start/);
  assert.deepEqual(state.accountOf('postgres'), { user: 'marina', password: null });
});

test('engines without marina-managed auth store the account and say so', async () => {
  const ctx = buildCtx(engines.mongodb, { major: '7.0', version: '7.0.45', port: await closedPort() });
  const result = await changeAccount(ctx, { password: 'docpass' });
  assert.deepEqual(result.applied, []);
  assert.match(result.notes.join(' '), /no marina-managed auth/);
  assert.deepEqual(state.accountOf('mongodb'), { user: null, password: 'docpass' });
});

test('redis stores the password, writes its config and defers the restart', async () => {
  const port = await closedPort();
  state.setPort('redis', '7', port);
  const ctx = buildCtx(engines.redis, { major: '7', version: '7.4.11' });
  const result = await changeAccount(ctx, { password: 'redispass' });

  assert.deepEqual(result.applied, []);
  assert.match(result.notes.join(' '), /applies on next start/);
  assert.deepEqual(state.accountOf('redis'), { user: null, password: 'redispass' });

  const conf = path.join(HOME, 'etc', 'redis', '7', 'redis.conf');
  assert.ok(fs.existsSync(conf), 'redis.conf should be generated by the settings change');
  const text = fs.readFileSync(conf, 'utf8');
  assert.match(text, new RegExp(`^port ${port}$`, 'm'));
  // README documents "Redis 写 requirepass" — the stored password must reach the server config
  assert.match(text, /^requirepass\b.*redispass/m);
});

test('changePort is a no-op when the requested port is the current one', async () => {
  const port = await closedPort();
  const ctx = buildCtx(engines.mongodb, { major: '7.0', version: '7.0.45', port });
  const result = await changePort(ctx, port);
  assert.deepEqual(result, { port, same: true, restarted: false });
  // no config should have been generated for an unchanged port
  assert.equal(fs.existsSync(path.join(HOME, 'etc', 'mongodb', '7.0', 'mongod.conf')), false);
});

test('changePort validates the new value before probing the network', async () => {
  const ctx = buildCtx(engines.mongodb, { major: '7.0', version: '7.0.45', port: await closedPort() });
  await assert.rejects(changePort(ctx, 70000), /port must be 1\.\.65535/);
  await assert.rejects(changePort(ctx, 'not-a-port'), /port must be 1\.\.65535/);
});

test('changePort refuses a port that already has a listener', async () => {
  const { srv, port: busy } = await listeningPort();
  try {
    const ctx = buildCtx(engines.memcached, { major: '1', version: '1.6.45', port: await closedPort() });
    await assert.rejects(changePort(ctx, busy), new RegExp(`port ${busy} is already in use`));
    assert.equal(state.portOf('memcached', '1', 11211), 11211);
  } finally {
    await new Promise((resolve) => srv.close(resolve));
  }
});

test('changePort persists the new port and regenerates the config', async () => {
  const previous = await closedPort();
  state.setPort('mongodb', '7.0', previous);
  const ctx = buildCtx(engines.mongodb, { major: '7.0', version: '7.0.45' });
  assert.equal(ctx.port, previous);

  let target;
  do target = await closedPort(); while (target === previous);

  const result = await changePort(ctx, target);
  assert.deepEqual(result, { port: target, same: false, restarted: false });
  assert.equal(state.portOf('mongodb', '7.0'), target);

  const conf = fs.readFileSync(path.join(HOME, 'etc', 'mongodb', '7.0', 'mongod.conf'), 'utf8');
  assert.match(conf, new RegExp(`^  port: ${target}$`, 'm'));
  assert.doesNotMatch(conf, new RegExp(`^  port: ${previous}$`, 'm'));
});
