// PATH shims: runtime/shims/<bin> -> marina shim-exec <bin>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirs, ensureDirs } from './paths.js';
import { engineList, activeCtx } from './registry.js';
import { findBin } from './archive.js';
import { IS_WIN } from './platform.js';

const CLI = fileURLToPath(new URL('../bin/marina.js', import.meta.url));

export function shimScript(bin) {
  if (IS_WIN) {
    return `@echo off\r\nrem generated by marina — resolves ${bin} from the active version\r\n"${process.execPath}" "${CLI}" shim-exec "${bin}" %*\r\n`;
  }
  return `#!/bin/sh
# generated by marina — resolves ${bin} from the active version
exec ${JSON.stringify(process.execPath)} ${JSON.stringify(CLI)} shim-exec ${JSON.stringify(bin)} "$@"
`;
}

export function installShims() {
  ensureDirs();
  const created = [];
  for (const engine of engineList) {
    const ctx = activeCtx(engine);
    if (!ctx || !ctx.root) continue;
    for (const bin of engine.clientBins) {
      const target = findBin(ctx.root, [bin]);
      if (!target) continue;
      const dest = path.join(dirs.shims, IS_WIN ? `${bin}.cmd` : bin);
      fs.writeFileSync(dest, shimScript(bin), { mode: 0o755 });
      created.push({ bin, target });
    }
  }
  return created;
}

export function resolveBin(bin) {
  for (const engine of engineList) {
    if (!engine.clientBins.includes(bin)) continue;
    const ctx = activeCtx(engine);
    if (!ctx || !ctx.root) return null;
    const found = findBin(ctx.root, [bin]);
    return found ? { engine, ctx, path: found } : null;
  }
  return null;
}

export function shellenv() {
  if (IS_WIN) {
    return `$env:MARINA_HOME = "${dirs.root}"\n$env:PATH = "${dirs.shims};$env:PATH"`;
  }
  return `export MARINA_HOME=${JSON.stringify(dirs.root)}\nexport PATH="${dirs.shims}:$PATH"`;
}
