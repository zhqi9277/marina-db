// Windows host: CIM command lines, taskkill, junctions, and a logon scheduled task.
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { defineHost } from './define.js';
import { xmlEscape } from './escape.js';
import { linkDir, linkFile } from './fs.js';
import { signalTerminate } from './posix.js';

const TASK_NAME = 'marina-autostart';

/** PowerShell Expand-Archive arguments. Single-quoted strings are literal, so only `'` is doubled. */
export function expandArchiveArgs(tarball, destDir) {
  const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
  return [
    '-NoProfile',
    '-NonInteractive',
    '-Command',
    `Expand-Archive -LiteralPath ${quote(tarball)} -DestinationPath ${quote(destDir)} -Force -ErrorAction Stop`,
  ];
}

/** argv for `Get-CimInstance Win32_Process`. pid must be an integer; nothing else is interpolated. */
export function winProcessCommand(pid) {
  const id = Number(pid);
  if (!Number.isInteger(id) || id <= 0) return null;
  return [
    '-NoProfile',
    '-NonInteractive',
    '-Command',
    `Get-CimInstance Win32_Process -Filter 'ProcessId=${id}' | Select-Object -ExpandProperty CommandLine`,
  ];
}

/** CIM prints the command line and a trailing newline. Empty output means "could not see it". */
export function parseWinCommandLine(stdout) {
  const command = String(stdout || '').replace(/\u0000/g, '').replace(/\r/g, '').trim();
  if (!command) return null;
  return { command, cwd: null };
}

function processDetails(pid) {
  const args = winProcessCommand(pid);
  if (!args) return null;
  try {
    const res = spawnSync('powershell', args, { encoding: 'utf8', timeout: 4000, windowsHide: true });
    if (res.error || res.status !== 0) return null;
    return parseWinCommandLine(res.stdout);
  } catch {
    return null;
  }
}

function terminate(pid, mode) {
  // Off Windows (unit tests importing this host) fall back to POSIX signals.
  // On Windows, taskkill /F is TerminateProcess; without /F it asks the process to close.
  if (process.platform !== 'win32') return signalTerminate(pid, mode);
  const args = mode === 'kill' ? ['/F', '/T', '/PID', String(pid)] : ['/T', '/PID', String(pid)];
  try {
    const res = spawnSync('taskkill', args, { encoding: 'utf8', windowsHide: true });
    return !res.error && res.status === 0;
  } catch {
    return false;
  }
}

function winShimScript(bin, node, cli) {
  return `@echo off\r\nrem generated by marina — resolves ${bin} from the active version\r\n"${node}" "${cli}" shim-exec "${bin}" %*\r\n`;
}

function winShellenv(home, shims) {
  return `$env:MARINA_HOME = "${home}"\n$env:PATH = "${shims};$env:PATH"`;
}

export const win32 = defineHost({
  id: 'win32',
  label: 'Windows',
  pathCaseInsensitive: true,
  unixSocket: false,
  fork: false,
  posixSignals: false,
  exe: (name) => `${name}.exe`,
  libInspector: () => null,
  linkDir: (target, link) => linkDir(target, link, 'junction'),
  linkFile,
  processDetails,
  terminate,
  forceVerb: 'forced termination',
  killHint(pid) {
    return `taskkill /F /PID ${pid}`;
  },
  shimFileName: (bin) => `${bin}.cmd`,
  shimScript: winShimScript,
  shellenv: winShellenv,
  unitTarget() {
    const dir = process.env.MARINA_SCHTASKS_DIR || path.join(os.homedir(), 'AppData', 'Roaming', 'marina');
    return { manager: 'schtasks', taskName: TASK_NAME, dir, file: path.join(dir, 'marina-autostart.xml') };
  },
  renderUnit(ids, _target, { node, cli }) {
    const argumentsText = `"${cli}" start --autostart`;
    return `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>marina autostart databases (${xmlEscape(ids.join(', '))})</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>false</StartWhenAvailable>
    <Enabled>true</Enabled>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>${xmlEscape(node)}</Command>
      <Arguments>${xmlEscape(argumentsText)}</Arguments>
    </Exec>
  </Actions>
</Task>
`;
  },
  loadAutostart(target, run) {
    return [run('schtasks', ['/Create', '/TN', target.taskName || TASK_NAME, '/XML', target.file, '/F'])];
  },
  unloadAutostart(target, run) {
    return [run('schtasks', ['/Delete', '/TN', target.taskName || TASK_NAME, '/F'])];
  },
  zipExtractArgs(tarball, destDir) {
    if (!String(tarball).endsWith('.zip')) return null;
    return { cmd: 'powershell', args: expandArchiveArgs(tarball, destDir) };
  },
});
