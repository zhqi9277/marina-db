// Shared POSIX process, signal, and shell behavior for Linux and macOS.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';

function readProc(pid) {
  try {
    const argv = fs.readFileSync(`/proc/${pid}/cmdline`, 'utf8').split('\0').filter(Boolean);
    let cwd = null;
    try {
      cwd = fs.realpathSync(fs.readlinkSync(`/proc/${pid}/cwd`));
    } catch {}
    if (argv.length || cwd) return { command: argv.join(' '), cwd };
  } catch {}
  return null;
}

function readPs(pid) {
  try {
    const res = spawnSync('ps', ['-p', String(pid), '-o', 'command='], { encoding: 'utf8', timeout: 2000 });
    if (!res.error && res.status === 0) {
      const command = (res.stdout || '').trim();
      if (command) return { command, cwd: null };
    }
  } catch {}
  return null;
}

function readLsof(pid) {
  try {
    const res = spawnSync('lsof', ['-p', String(pid), '-a', '-d', 'cwd', '-Fn'], { encoding: 'utf8', timeout: 3000 });
    if (!res.error && res.status === 0) {
      const line = (res.stdout || '').split('\n').find((row) => row.startsWith('n'));
      if (line) return { command: null, cwd: line.slice(1) };
    }
  } catch {}
  return null;
}

/** Linux reads /proc first. macOS has no /proc, so it starts at ps. */
export function posixProcessDetails(pid, { proc = false } = {}) {
  if (proc) {
    const fromProc = readProc(pid);
    if (fromProc) return fromProc;
  }
  return readPs(pid) || readLsof(pid);
}

export function signalTerminate(pid, mode) {
  const signal = mode === 'kill' ? 'SIGKILL' : 'SIGTERM';
  try {
    process.kill(pid, signal);
    return true;
  } catch {
    return false;
  }
}

export const POSIX_STOP = {
  forceVerb: 'SIGKILL',
  killHint(pid) {
    return `kill -9 ${pid}`;
  },
};

export function posixShimScript(bin, node, cli) {
  return `#!/bin/sh
# generated by marina — resolves ${bin} from the active version
exec ${JSON.stringify(node)} ${JSON.stringify(cli)} shim-exec ${JSON.stringify(bin)} "$@"
`;
}

export function posixShellenv(home, shims) {
  return `export MARINA_HOME=${JSON.stringify(home)}\nexport PATH="${shims}:$PATH"`;
}
