// Redis: no datadir bootstrap, config file drives everything (daemonize yes).
import fs from 'node:fs';
import path from 'node:path';
import { spawnAsync, findBin } from '../archive.js';
import { mkdirp } from '../paths.js';

export default {
  key: 'redis',
  label: 'Redis',
  kind: 'kv',
  manifestName: 'redis',
  defaultMajor: '7',
  defaultPort: 6379,
  serverBin: ['redis-server'],
  markers: ['bin/redis-server'],
  clientBins: ['redis-cli', 'redis-benchmark', 'redis-check-aof', 'redis-check-rdb', 'redis-sentinel'],
  primaryClient: 'redis-cli',
  hasDataDir: true,

  pidPath(ctx) {
    return ctx.pidFile;
  },

  readPid(ctx) {
    try {
      const pid = parseInt(fs.readFileSync(ctx.pidFile, 'utf8').trim(), 10);
      return Number.isFinite(pid) ? pid : null;
    } catch {
      return null;
    }
  },

  confPath(ctx) {
    return ctx.confFile;
  },

  renderConfig(ctx) {
    return `# generated by marina — edit, then: marina restart redis
bind 127.0.0.1 ::1
protected-mode yes
port ${ctx.port}
tcp-backlog 511
timeout 0
tcp-keepalive 300
daemonize yes
pidfile ${ctx.pidFile}
loglevel notice
logfile ${ctx.logFile}
databases 16
always-show-logo no
dir ${ctx.dataDir}/
dbfilename dump.rdb
save 900 1
save 300 10
save 60 10000
appendonly no
`;
  },

  async init(ctx) {
    mkdirp(ctx.dataDir);
    return { skipped: true };
  },

  clientArgs(ctx) {
    return ['-p', String(ctx.port)];
  },

  startArgs(ctx) {
    return [ctx.confFile];
  },

  stopCommand(ctx) {
    const cli = findBin(ctx.root, ['redis-cli']);
    if (!cli) return null;
    return { cmd: cli, args: ['-p', String(ctx.port), 'shutdown', 'save'] };
  },

  account() {
    return {
      user: null,
      password: null,
      mode: 'disabled',
      note: 'no requirepass; protected-mode, binds 127.0.0.1',
    };
  },

  async probe(ctx) {
    const cli = findBin(ctx.root, ['redis-cli']);
    if (!cli) return null;
    const res = await spawnAsync(cli, ['-p', String(ctx.port), 'ping']);
    if (res.code === 0 && /PONG/i.test(res.stdout)) return true;
    return false;
  },
};
