// Redis: no datadir bootstrap. The host decides whether Redis daemonizes.
import fs from 'node:fs';
import { spawnAsync, findBin } from '../install/archive.js';
import { mkdirp } from '../core/paths.js';
import { host, IS_WIN } from '../core/platform.js';

const recordPid = !host.capabilities.fork;

export function cygwinPath(file) {
  return file.replace(/\\/g, '/').replace(/^([a-z]):\//i, (_, drive) => `/cygdrive/${drive.toLowerCase()}/`);
}

/**
 * redis.conf quoting: bare words cannot contain spaces, quoted values accept
 * \" / \\ and \xHH escapes. A password must never break out into a new
 * directive, so anything unusual is quoted and escaped.
 */
function redisArg(value) {
  const raw = String(value);
  if (!/[\s"\\\x00-\x1f\x7f]/.test(raw)) return raw;
  const escaped = raw
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\x00-\x1f\x7f]/g, (ch) => `\\x${ch.charCodeAt(0).toString(16).padStart(2, '0')}`);
  return `"${escaped}"`;
}

export default {
  key: 'redis',
  label: 'Redis',
  kind: 'kv',
  manifestName: 'redis',
  defaultMajor: '7',
  defaultPort: 6379,
  serverBin: ['redis-server'],
  markers: ['bin/redis-server'],
  clientBins: ['redis-cli', 'redis-benchmark', 'redis-check-aof', 'redis-check-rdb', 'redis-sentinel'],
  primaryClient: 'redis-cli',
  hasDataDir: true,
  recordPid,

  readPid(ctx) {
    try {
      const pid = parseInt(fs.readFileSync(ctx.pidFile, 'utf8').trim(), 10);
      return Number.isFinite(pid) ? pid : null;
    } catch {
      return null;
    }
  },

  renderConfig(ctx) {
    const pass = ctx.account?.password;
    const requirepass = pass ? `requirepass ${redisArg(pass)}\n` : '';
    return `# generated by marina — edit, then: marina restart redis
bind 127.0.0.1 ::1
protected-mode yes
tcp-backlog 511
timeout 0
tcp-keepalive 300
daemonize ${recordPid ? 'no' : 'yes'}
loglevel notice
databases 16
always-show-logo no
dbfilename dump.rdb
save 900 1
save 300 10
save 60 10000
${requirepass}appendonly no
`;
  },

  async init(ctx) {
    mkdirp(ctx.dataDir);
    return { skipped: true };
  },

  clientArgs(ctx) {
    const pass = ctx.account?.password;
    return pass ? ['-p', String(ctx.port), '-a', pass, '--no-auth-warning'] : ['-p', String(ctx.port)];
  },

  startArgs(ctx) {
    if (IS_WIN) return [
      cygwinPath(ctx.confFile),
      '--port', String(ctx.port),
      '--daemonize', 'no',
      '--logfile', cygwinPath(ctx.logFile),
      '--dir', cygwinPath(ctx.dataDir),
    ];
    return [
      ctx.confFile,
      '--port', String(ctx.port),
      ...(recordPid ? ['--daemonize', 'no'] : ['--pidfile', ctx.pidFile]),
      '--logfile', ctx.logFile,
      '--dir', ctx.dataDir,
    ];
  },

  stopCommand(ctx) {
    const cli = findBin(ctx.root, ['redis-cli']);
    if (!cli) return null;
    const pass = ctx.account?.password;
    return {
      cmd: cli,
      args: [...(pass ? ['-a', pass, '--no-auth-warning'] : []), '-p', String(ctx.port), 'shutdown', 'save'],
    };
  },

  account(ctx) {
    const pass = ctx.account?.password;
    return {
      user: null,
      password: pass ?? null,
      mode: pass ? 'password' : 'disabled',
      note: pass ? 'requirepass, applied on restart' : 'no requirepass; protected-mode, binds 127.0.0.1',
    };
  },

  async probe(ctx) {
    const cli = findBin(ctx.root, ['redis-cli']);
    if (!cli) return null;
    const pass = ctx.account?.password;
    const res = await spawnAsync(cli, [...(pass ? ['-a', pass, '--no-auth-warning'] : []), '-p', String(ctx.port), 'ping']);
    if (res.code === 0 && /PONG/i.test(res.stdout)) return true;
    return false;
  },
};
