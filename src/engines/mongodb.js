// MongoDB: no datadir bootstrap; mongod --fork writes the pid file itself.
import fs from 'node:fs';
import { spawnAsync, findBin } from '../archive.js';
import { mkdirp } from '../paths.js';
import { IS_WIN } from '../platform.js';

export default {
  key: 'mongodb',
  label: 'MongoDB',
  kind: 'doc',
  manifestName: 'mongodb',
  defaultMajor: '7.0',
  defaultPort: 27017,
  serverBin: ['mongod'],
  markers: ['bin/mongod'],
  clientBins: ['mongod', 'mongos', 'mongoexport', 'mongoimport', 'mongodump', 'mongorestore'],
  primaryClient: 'mongosh', // shipped as a separate package
  hasDataDir: true,

  pidPath(ctx) {
    return ctx.pidFile;
  },

  readPid(ctx) {
    try {
      const pid = parseInt(fs.readFileSync(ctx.pidFile, 'utf8').trim(), 10);
      return Number.isFinite(pid) ? pid : null;
    } catch {
      return null;
    }
  },

  confPath(ctx) {
    return ctx.confFile;
  },

  renderConfig(ctx) {
    return `# generated by marina — mongod startup flags live here for reference
net:
  bindIp: 127.0.0.1
  port: ${ctx.port}
storage:
  dbPath: ${ctx.dataDir}
systemLog:
  destination: file
  path: ${ctx.logFile}
  logAppend: true
processManagement:
  fork: true
  pidFilePath: ${ctx.pidFile}
`;
  },

  async init(ctx) {
    mkdirp(ctx.dataDir);
    mkdirp(ctx.logDir);
    return { skipped: true };
  },

  clientArgs(ctx) {
    const args = ['--host', '127.0.0.1', '--port', String(ctx.port)];
    const acct = ctx.account;
    if (acct?.user) args.push('--username', acct.user, '--password', acct.password || '', '--authenticationDatabase', 'admin');
    return args;
  },

  startArgs(ctx) {
    const args = [
      '--dbpath', ctx.dataDir,
      '--port', String(ctx.port),
      '--bind_ip', '127.0.0.1',
      '--logpath', ctx.logFile,
      '--logappend',
      '--pidfilepath', ctx.pidFile,
    ];
    if (!IS_WIN) args.push('--fork'); // Windows has no fork; marina detaches instead
    return args;
  },

  stopCommand() {
    return null; // generic SIGTERM path: mongod shuts down cleanly on SIGTERM
  },

  account(ctx) {
    const acct = ctx.account || {};
    return {
      user: acct.user ?? null,
      password: acct.password ?? null,
      mode: acct.user ? 'stored' : 'disabled',
      note: 'stored only; marina does not enable mongod --auth',
    };
  },

  async probe(ctx) {
    const mongosh = findBin(ctx.root, ['mongosh']);
    if (!mongosh) return null;
    const args = ['--quiet', '--host', '127.0.0.1', '--port', String(ctx.port)];
    if (ctx.account?.user) args.push('--username', ctx.account.user, '--password', ctx.account.password || '', '--authenticationDatabase', 'admin');
    args.push('--eval', 'db.runCommand({ping:1}).ok');
    const res = await spawnAsync(mongosh, args);
    return res.code === 0 && /1/.test(res.stdout);
  },
};
